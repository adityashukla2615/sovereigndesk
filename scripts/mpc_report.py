"""Write docs/MPC_BACKTEST.md: the MPC predictor's walk-forward backtest on the real seed.

    py tasks.py mpc-report

Boots the data layer offline on data/seed (no network) in a throwaway database, fits the
predictor exactly as the terminal does, and writes the report: the sample, the features, the
three models and the two naive baselines, their scores and confusion matrices, every forecast,
and the forecast for the next scheduled meeting from the data alone (no simulation).
"""

import io
import math
import sys
import tempfile
from datetime import date
from pathlib import Path
from typing import Any

from fastapi.testclient import TestClient

from app.config import REPO_ROOT, Settings
from app.data.seed import read_manifest
from app.main import create_app
from app.sim.mpc import FEATURE_LABELS, FEATURES, MpcModel, build_mpc, features_at, repo_on
from sovereign_engine.predict import CLASSES

OUT = REPO_ROOT / "docs" / "MPC_BACKTEST.md"
MODELS = ("ordered logit", "xgboost", "taylor", "repeat last", "always hold")
SHORT = ("big cut", "cut", "hold", "hike", "big hike")


def _fmt(value: float, digits: int = 2) -> str:
    return "—" if not math.isfinite(value) else f"{value:.{digits}f}"


def _confusion(matrix: Any) -> list[str]:
    head = "| actual \\ called | " + " | ".join(SHORT) + " |"
    rule = "|---|" + "---:|" * len(SHORT)
    rows = [
        f"| {SHORT[a]} | " + " | ".join(str(int(n)) for n in matrix[a]) + " |" for a in range(5)
    ]
    return [head, rule, *rows]


def render(model: MpcModel, seed_date: str) -> str:
    data, bt, p = model.dataset, model.backtest, model.params
    counts = [int((data.classes == k).sum()) for k in range(5)]
    lines = [
        "# MPC predictor: walk-forward backtest",
        "",
        "Generated by `py tasks.py mpc-report` from the committed seed "
        f"(data snapshot of {seed_date}). Nothing here is hand-edited.",
        "",
        "## Sample",
        "",
        f"{len(data.dates)} repo-rate decisions from {data.dates[0]} to {data.dates[-1]}: "
        + ", ".join(f"{n} {c}" for n, c in zip(counts, CLASSES, strict=True))
        + f". {sum(1 for s in data.scheduled if not s)} were off-cycle. A big move is more than "
        "25 bp. Decisions before the MPC's first (4 Oct 2016) were the Governor's.",
        "",
        "## Features (what was public the day before each decision)",
        "",
        "| Feature | Definition |",
        "|---|---|",
        *(f"| `{f}` | {FEATURE_LABELS[f]} |" for f in FEATURES),
        "",
        "CPI is MoSPI's (2012 base to Dec 2025, 2024 base from Jan 2026), usable after the 12th "
        "of the month after; GDP is MoSPI's (2011-12 base, then 2022-23), usable from the start "
        "of the third month after the quarter. The money-market features average the 14 days "
        "before the decision; the T-bill is the last 91-day auction before it. Later revisions "
        "to CPI and GDP are not undone.",
        "",
        "## Models",
        "",
        f"- **Taylor rule**: i* = r* + π + 0.5(π − π*) + 0.5·gap with r* = {p.r_star:.1%} and "
        f"π* = {p.pi_star:.0%}; it moves a quarter of the way to i* per meeting, in 25 bp steps, "
        "at most 50 bp. The output gap is a one-sided HP filter (λ = 1600) on four-quarter real "
        "GDP. Deterministic, so its Brier score counts every miss in full.",
        f"- **Ordered logit**: cumulative logit on the standardised features with an L2 penalty "
        f"(λ = {p.l2:g}) on the slopes; at λ = 0 it is statsmodels' `OrderedModel`.",
        "- **XGBoost**: 200 trees of depth 2, learning rate 0.05, row and column subsampling 0.8, "
        "L2 leaf penalty 5.",
        "",
        "## Backtest",
        "",
        f"Each of the {bt.rows.size} decisions from {data.dates[int(bt.rows[0])]} on is forecast "
        f"by models fitted on the decisions before it only (expanding window, the first "
        f"{p.backtest_start} for training at the start).",
        "",
        "| Forecast | Hit rate | Macro-F1 | Brier |",
        "|---|---:|---:|---:|",
        *(
            f"| {name} | {r.accuracy:.0%} | {r.macro_f1:.2f} | {r.brier:.2f} |"
            for name in MODELS
            if (r := bt.reports.get(name)) is not None
        ),
        "",
        "Hit rate is the share called exactly; macro-F1 averages F1 over the classes that "
        "occurred, so always holding scores poorly however common holds are; the Brier score "
        "(0 best, 2 worst) rewards calibrated probabilities.",
        "",
    ]
    for name in MODELS[:3]:
        lines += [f"### {name}: confusion matrix", "", *_confusion(bt.reports[name].confusion), ""]
    lines += [
        "### Every forecast",
        "",
        "| Decision | Move | Actual | Logit | P(actual) | XGBoost | P(actual) | Taylor |",
        "|---|---:|---|---|---:|---|---:|---|",
    ]
    for j, row in enumerate(bt.rows.tolist()):
        actual = int(bt.actual[j])
        lo, xg = bt.reports["ordered logit"], bt.reports["xgboost"]
        tag = "" if data.scheduled[row] else " (off-cycle)"
        lines.append(
            f"| {data.dates[row]}{tag} | {data.change[row] * 1e4:+.0f} bp | {SHORT[actual]} | "
            f"{SHORT[int(lo.predicted[j])]} | {lo.probabilities[j, actual]:.2f} | "
            f"{SHORT[int(xg.predicted[j])]} | {xg.probabilities[j, actual]:.2f} | "
            f"{SHORT[int(bt.reports['taylor'].predicted[j])]} |"
        )
    today = date.fromisoformat(seed_date[:10])
    nxt = model.next_meeting(today)
    features, gap = features_at(
        model.inputs, today, params=p, last_change_bp=float(data.change[-1]) * 1e4
    )
    forecast = model.forecast(features, repo_on(model.inputs, today), gap)
    lines += [
        "",
        f"## Next meeting: {nxt or 'not yet scheduled'}",
        "",
        f"From the data as of {today}, before any simulation:",
        "",
        "| Model | " + " | ".join(SHORT) + " |",
        "|---|" + "---:|" * 5,
        *(
            f"| {name} | " + " | ".join(f"{v:.0%}" for v in probs) + " |"
            for name, probs in forecast.items()
        ),
        "",
        "| Feature | Now |",
        "|---|---:|",
        *(f"| {FEATURE_LABELS[f]} | {_fmt(features[f])} |" for f in FEATURES),
        "",
        "## Core CPI weights",
        "",
        "MoSPI does not publish weights with the indices, so they are recovered by constrained "
        "least squares from the published general and component indices:",
        "",
    ]
    for w in model.inputs.weights:
        shares = ", ".join(f"{k} {v:.2%}" for k, v in w.excluded.items())
        lines.append(
            f"- base {w.base}: excluded {shares}; rebuild error {w.rmse:.3f} index points "
            f"over {w.months} months"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    if isinstance(sys.stdout, io.TextIOWrapper):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    with tempfile.TemporaryDirectory() as tmp:
        overrides: dict[str, Any] = {
            "_env_file": None,
            "env": "test",
            "fred_api_key": None,
            "database_url": f"sqlite:///{(Path(tmp) / 'report.db').as_posix()}",
            "data_dir": REPO_ROOT / "data",
            "scheduler_enabled": False,
            "offline": True,
            "sim_enabled": False,
        }
        settings = Settings(**overrides)
        with TestClient(create_app(settings)) as client:
            service = client.app.state.data  # type: ignore[attr-defined]
            model = build_mpc(service)
    manifest = read_manifest(REPO_ROOT / "data" / "seed")
    seed_date = manifest.generated_at if manifest else date.today().isoformat()
    OUT.write_text(render(model, seed_date), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}")
    for name in MODELS:
        r = model.backtest.reports[name]
        print(f"  {name:13s} hit {r.accuracy:.0%}  macro-F1 {r.macro_f1:.2f}  Brier {r.brier:.2f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
